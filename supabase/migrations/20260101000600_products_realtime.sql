-- Live stock: the storefront already subscribes to product changes for the
-- "In stock" badge, and products_read already allows authenticated reads.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'products'
  ) then
    alter publication supabase_realtime add table public.products;
  end if;
end $$;
