import { Router } from "express";

import { ApiError } from "../lib/errors.js";
import { supabase } from "../lib/supabase.js";
import { auth, requireRole } from "../middleware.js";
import { roundMoney } from "../lib/fee.js";

/* FR-18. The dashboard summary (staff and admin) and the four reports (admin).
   Sales and top-product totals are aggregated in SQL so a date range never loads
   every order into Node; inventory and low stock read the products table.

   `format=csv` is generated by hand, as the blueprint asks, and returned as a
   download. */

export const reportsRouter = Router();

reportsRouter.use(auth);

const MAX_ROWS = 1000;
const DEFAULT_RANGE_DAYS = 30;
const DATE_ONLY = /^\d{4}-\d{2}-\d{2}$/;
const DAY_MS = 24 * 60 * 60 * 1000;
const TYPES = ["sales", "inventory", "low-stock", "top-products"];

function badRequest(path, message) {
  return new ApiError(400, "Validation failed", [{ path, message }]);
}

/** `from`/`to` accept an ISO date or timestamp. A bare `to` date includes that whole day. */
function readRange(query) {
  let to = new Date();
  let from = new Date(to.getTime() - DEFAULT_RANGE_DAYS * DAY_MS);

  if (query.to) {
    const raw = String(query.to);
    to = new Date(raw);
    if (Number.isNaN(to.getTime())) throw badRequest("to", "Use an ISO date, for example 2026-11-01.");
    if (DATE_ONLY.test(raw)) to = new Date(to.getTime() + DAY_MS);
  }

  if (query.from) {
    from = new Date(String(query.from));
    if (Number.isNaN(from.getTime())) {
      throw badRequest("from", "Use an ISO date, for example 2026-11-01.");
    }
  }

  if (from >= to) throw badRequest("from", "The start of the range has to come before the end.");

  return { from: from.toISOString(), to: to.toISOString() };
}

function toCsv(columns, rows) {
  const cell = (value) => {
    const text = value === null || value === undefined ? "" : String(value);
    return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
  };

  const header = columns.map((column) => cell(column.label)).join(",");
  const body = rows.map((row) => columns.map((column) => cell(column.value(row))).join(","));

  return [header, ...body].join("\r\n");
}

function respond(res, { type, format, columns, rows }) {
  if (format === "csv") {
    const today = new Date().toISOString().slice(0, 10);
    res.setHeader("Content-Type", "text/csv; charset=utf-8");
    res.setHeader("Content-Disposition", `attachment; filename="${type}-${today}.csv"`);
    return res.send(toCsv(columns, rows));
  }

  return res.json({ data: rows });
}

function readFormat(query) {
  const format = query.format ? String(query.format) : "json";
  if (format !== "json" && format !== "csv") {
    throw badRequest("format", "Use format=json or format=csv.");
  }
  return format;
}

reportsRouter.get("/summary", requireRole("admin", "staff"), async (req, res) => {
  const [low, recent, customers, orders] = await Promise.all([
    supabase().rpc("low_stock_products"),
    supabase()
      .from("orders")
      .select("id, status, total_amount, fulfillment_type, created_at")
      .order("created_at", { ascending: false })
      .limit(5),
    supabase()
      .from("profiles")
      .select("id", { count: "exact", head: true })
      .eq("role", "customer")
      .eq("is_active", true),
    supabase().from("orders").select("id", { count: "exact", head: true }),
  ]);

  if (low.error || recent.error) throw new ApiError(500, "Could not load the dashboard");

  // Staff run the shop day to day; money totals are admin only (C3).
  let sales = null;
  if (req.user.role === "admin") {
    const { from, to } = readRange({});
    const { data, error } = await supabase().rpc("report_sales", { from_date: from, to_date: to });
    if (error) throw new ApiError(500, "Could not load the sales summary");

    const revenue = (data ?? []).reduce((sum, row) => sum + Number(row.revenue), 0);
    const orderCount = (data ?? []).reduce((sum, row) => sum + Number(row.orders), 0);

    sales = {
      revenue: roundMoney(revenue),
      orders: orderCount,
      average: orderCount === 0 ? 0 : roundMoney(revenue / orderCount),
      days: data ?? [],
    };
  }

  const lowStock = low.data ?? [];

  res.json({
    data: {
      sales,
      low_stock: lowStock,
      recent_orders: recent.data ?? [],
      counts: {
        customers: customers.count ?? 0,
        orders: orders.count ?? 0,
        low_stock: lowStock.length,
      },
    },
  });
});

reportsRouter.get("/:type", requireRole("admin"), async (req, res) => {
  const type = String(req.params.type);
  const format = readFormat(req.query);

  if (type === "sales") {
    const { from, to } = readRange(req.query);
    const { data, error } = await supabase().rpc("report_sales", { from_date: from, to_date: to });
    if (error) throw new ApiError(500, "Could not build the sales report");

    const rows = (data ?? []).map((row) => ({
      day: row.day,
      orders: Number(row.orders),
      revenue: roundMoney(Number(row.revenue)),
    }));

    return respond(res, {
      type,
      format,
      rows,
      columns: [
        { label: "Day", value: (row) => row.day },
        { label: "Orders", value: (row) => row.orders },
        { label: "Revenue", value: (row) => row.revenue.toFixed(2) },
      ],
    });
  }

  if (type === "inventory") {
    const { data, error } = await supabase()
      .from("products")
      .select("id, name, unit, price, stock_qty, reorder_level")
      .is("deleted_at", null)
      .order("name")
      .limit(MAX_ROWS);

    if (error) throw new ApiError(500, "Could not build the inventory report");

    const rows = (data ?? []).map((product) => ({
      name: product.name,
      unit: product.unit,
      price: roundMoney(product.price),
      stock_qty: product.stock_qty,
      stock_value: roundMoney(Number(product.price) * product.stock_qty),
      reorder_level: product.reorder_level,
      low: product.stock_qty <= product.reorder_level,
    }));

    return respond(res, {
      type,
      format,
      rows,
      columns: [
        { label: "Product", value: (row) => row.name },
        { label: "Unit", value: (row) => row.unit },
        { label: "Price", value: (row) => row.price.toFixed(2) },
        { label: "Stock", value: (row) => row.stock_qty },
        { label: "Stock value", value: (row) => row.stock_value.toFixed(2) },
        { label: "Reorder at", value: (row) => row.reorder_level },
        { label: "Low", value: (row) => (row.low ? "yes" : "no") },
      ],
    });
  }

  if (type === "low-stock") {
    const { data, error } = await supabase().rpc("low_stock_products");
    if (error) throw new ApiError(500, "Could not build the low-stock report");

    const rows = (data ?? []).map((product) => ({
      name: product.name,
      unit: product.unit,
      stock_qty: product.stock_qty,
      reorder_level: product.reorder_level,
      shortfall: Math.max(product.reorder_level - product.stock_qty, 0),
    }));

    return respond(res, {
      type,
      format,
      rows,
      columns: [
        { label: "Product", value: (row) => row.name },
        { label: "Unit", value: (row) => row.unit },
        { label: "Stock", value: (row) => row.stock_qty },
        { label: "Reorder at", value: (row) => row.reorder_level },
        { label: "Shortfall", value: (row) => row.shortfall },
      ],
    });
  }

  if (type === "top-products") {
    const { from, to } = readRange(req.query);
    const { data, error } = await supabase().rpc("report_top_products", {
      from_date: from,
      to_date: to,
      max_rows: 10,
    });

    if (error) throw new ApiError(500, "Could not build the top-products report");

    const rows = (data ?? []).map((row) => ({
      name: row.name,
      quantity: Number(row.quantity),
      revenue: roundMoney(Number(row.revenue)),
    }));

    return respond(res, {
      type,
      format,
      rows,
      columns: [
        { label: "Product", value: (row) => row.name },
        { label: "Units", value: (row) => row.quantity },
        { label: "Revenue", value: (row) => row.revenue.toFixed(2) },
      ],
    });
  }

  throw new ApiError(404, `Unknown report type "${type}"`);
});
